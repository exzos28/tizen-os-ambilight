"""
Pre-build script for PlatformIO.

Runs `npm run build` inside the `web/` directory, then gzips
the resulting `web/dist/index.html` into a byte array in `src/web_ui.h`
so it can be compiled directly into the firmware binary.

PlatformIO runs this automatically via `extra_scripts = pre:scripts/embed_web.py`.
"""

Import('env')  # noqa: F821 — injected by PlatformIO

import gzip
import os
import subprocess
import sys

PROJECT_DIR = env['PROJECT_DIR']  # noqa: F821
WEB_DIR     = os.path.join(PROJECT_DIR, 'web')
DIST_FILE   = os.path.join(WEB_DIR, 'dist', 'index.html')
HEADER_FILE = os.path.join(PROJECT_DIR, 'src', 'web_ui.h')

# ---------------------------------------------------------------------------

print('\n[embed_web] Building React app...')

npm = 'npm.cmd' if sys.platform == 'win32' else 'npm'
result = subprocess.run([npm, 'run', 'build'], cwd=WEB_DIR)

if result.returncode != 0:
    print('[embed_web] ERROR: npm build failed.')
    sys.exit(1)

# ---------------------------------------------------------------------------

print('[embed_web] Embedding into web_ui.h...')

with open(DIST_FILE, 'rb') as f:
    html = f.read()

# Stored gzipped and served with Content-Encoding: gzip — about 3x smaller in flash.
# mtime=0 keeps the output identical between builds of the same input.
gz = gzip.compress(html, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(gz), 20):
    lines.append('    ' + ','.join(f'0x{b:02x}' for b in gz[i:i + 20]) + ',')

header = (
    '#pragma once\n'
    '// Auto-generated by scripts/embed_web.py — do not edit manually.\n'
    '#include <stddef.h>\n'
    '#include <stdint.h>\n\n'
    'static const uint8_t WEB_UI_GZ[] = {\n'
    + '\n'.join(lines) +
    '\n};\n'
    f'static const size_t WEB_UI_GZ_LEN = {len(gz)};\n'
)

with open(HEADER_FILE, 'w', encoding='utf-8') as f:
    f.write(header)

print(f'[embed_web] web_ui.h written ({len(html) / 1024:.1f} KB html, '
      f'{len(gz) / 1024:.1f} KB gzipped).\n')
