#!/usr/bin/env node
// Generates code from the protocol definition (protocol/schemas, protocol/constants.json):
//
//   packages/protocol/src/generated/types.ts      TypeScript types of every message
//   packages/protocol/src/generated/limits.ts     ESP32 setting ranges and defaults
//   packages/protocol/src/generated/constants.ts  constants.json
//   esp32/src/generated/ProtocolLimits.h          constexpr ranges/defaults and constants
//
//   npm run protocol:gen     (node protocol/scripts/gen.mjs [outDir])
//
// The generator understands a deliberately small subset of JSON Schema and fails on anything
// else, so a schema change can't silently produce wrong code. See protocol/README.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { SchemaSet, isMessageSchema, loadSchemas, protocolDir, readJson, repoRoot } from './schemas.mjs';

export const outputs = {
  types: 'packages/protocol/src/generated/types.ts',
  limits: 'packages/protocol/src/generated/limits.ts',
  constants: 'packages/protocol/src/generated/constants.ts',
  header: 'esp32/src/generated/ProtocolLimits.h',
};

const SETTINGS_FILE = 'esp32/settings.schema.json';
const COMMON_FILE = 'esp32/common.schema.json';

const TS_BANNER = '// Generated by protocol/scripts/gen.mjs from protocol/ — do not edit.\n// Regenerate with `npm run protocol:gen` at the repo root.\n';

// Keywords the generator understands. Annotations don't change the generated types.
const ANNOTATIONS = new Set(['$comment', 'title', 'description', 'default', 'writeOnly', 'x-unit']);
const KEYWORDS = new Set([
  ...ANNOTATIONS, '$schema', '$id', '$defs', '$ref', 'type', 'properties', 'required', 'additionalProperties',
  'items', 'enum', 'const', 'oneOf', 'anyOf', 'minimum', 'maximum', 'pattern', 'dependentRequired',
  'contentMediaType', 'contentSchema',
]);

// ------------------------------------------------------------------------------------ lint

function lint(schema, where) {
  for (const key of Object.keys(schema)) {
    if (!KEYWORDS.has(key)) throw new Error(`${where}: keyword "${key}" is not supported by gen.mjs`);
  }
  if (schema.$ref) {
    const extra = Object.keys(schema).filter((k) => k !== '$ref' && !ANNOTATIONS.has(k));
    if (extra.length) throw new Error(`${where}: only annotations may accompany $ref, found ${extra.join(', ')}`);
  }
  const types = [schema.type].flat();
  if (types.includes('object')) {
    if (schema.additionalProperties !== false) throw new Error(`${where}: objects must set "additionalProperties": false`);
    for (const r of schema.required ?? []) {
      if (!schema.properties?.[r]) throw new Error(`${where}: required "${r}" is not a property`);
    }
  }
  for (const [k, s] of Object.entries(schema.properties ?? {})) lint(s, `${where}/properties/${k}`);
  for (const [k, s] of Object.entries(schema.$defs ?? {})) lint(s, `${where}/$defs/${k}`);
  for (const [i, s] of (schema.oneOf ?? []).entries()) lint(s, `${where}/oneOf/${i}`);
  for (const [i, s] of (schema.anyOf ?? []).entries()) lint(s, `${where}/anyOf/${i}`);
  if (schema.items) lint(schema.items, `${where}/items`);
}

// ------------------------------------------------------------------------------- helpers

const isIdent = (s) => /^[A-Za-z_$][\w$]*$/.test(s);
const tsKey = (s) => (isIdent(s) ? s : `'${s}'`);
const tsLit = (v) => (typeof v === 'string' ? `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : JSON.stringify(v));
const upperSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toUpperCase();
const commentSafe = (s) => s.replace(/\*\//g, '*\\/');

// Word-wraps text to lines of at most width characters (longer words stay whole).
function wrap(text, width) {
  const out = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/).filter(Boolean)) {
      if (line && line.length + 1 + word.length > width) {
        out.push(line);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    }
    out.push(line);
  }
  return out;
}

// oneOf of consts with titles: a documented enum (titles are the member names).
const isConstUnion = (s) => Array.isArray(s.oneOf) && s.oneOf.every((b) => 'const' in b);

function jsdoc(a, indent = '') {
  const lines = a.description ? wrap(commentSafe(a.description), 96 - indent.length) : [];
  const tags = [];
  if ('minimum' in a) tags.push(`@minimum ${a.minimum}`);
  if ('maximum' in a) tags.push(`@maximum ${a.maximum}`);
  if (a.default !== undefined) tags.push(`@default ${JSON.stringify(a.default)}`);
  if (a['x-unit']) tags.push(`@unit ${a['x-unit']}`);
  if (a.pattern) tags.push(`@pattern ${commentSafe(a.pattern)}`);
  if (a.writeOnly) tags.push('@writeOnly');
  if (!lines.length && !tags.length) return '';
  if (lines.length === 1 && !tags.length) return `${indent}/** ${lines[0]} */\n`;
  const body = [...lines, ...(lines.length && tags.length ? [''] : []), ...tags];
  return `${indent}/**\n${body.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

// ---------------------------------------------------------------------------- generator

class Generator {
  constructor(schemas, constants) {
    this.set = new SchemaSet(schemas);
    this.constants = constants;
    this.named = new Map();   // 'file#pointer' → type name
    const names = new Set();
    const add = (key, name) => {
      if (!isIdent(name)) throw new Error(`${key}: title "${name}" is not a valid type name`);
      if (names.has(name)) throw new Error(`${key}: type name "${name}" is used twice`);
      names.add(name);
      this.named.set(key, name);
    };
    for (const [file, root] of schemas) {
      lint(root, file);
      if (isMessageSchema(root)) {
        if (!root.title) throw new Error(`${file}: a message schema needs a "title" (its type name)`);
        add(`${file}#`, root.title);
      }
      for (const [k, def] of Object.entries(root.$defs ?? {})) {
        if (def.title) add(`${file}#/$defs/${k}`, def.title);
      }
    }
  }

  // Merged annotations along the $ref chain; the referencing schema wins.
  annotations(schema, file) {
    let base = {};
    if (schema.$ref) {
      const r = this.set.resolve(file, schema.$ref);
      base = this.annotations(r.schema, r.file);
    }
    const own = {};
    for (const k of ['description', 'minimum', 'maximum', 'default', 'x-unit', 'pattern', 'writeOnly']) {
      if (k in schema) own[k] = schema[k];
    }
    return { ...base, ...own };
  }

  // The schema that carries the type, behind any $refs.
  typed(schema, file) {
    while (schema.$ref) ({ schema, file } = this.set.resolve(file, schema.$ref));
    return { schema, file };
  }

  tsType(schema, file) {
    if (schema.$ref) {
      const r = this.set.resolve(file, schema.$ref);
      return this.named.get(r.key) ?? this.tsType(r.schema, r.file);
    }
    if ('const' in schema) return tsLit(schema.const);
    if (schema.enum) return schema.enum.map(tsLit).join(' | ');
    const union = schema.oneOf ?? schema.anyOf;
    if (union) return union.map((s) => this.tsType(s, file)).join(' | ');
    if (schema.type === undefined) throw new Error(`${file}: schema without a type: ${JSON.stringify(schema)}`);
    return [schema.type].flat().map((t) => {
      switch (t) {
        case 'string': return 'string';
        case 'integer':
        case 'number': return 'number';
        case 'boolean': return 'boolean';
        case 'null': return 'null';
        case 'array': {
          const item = this.tsType(schema.items, file);
          return /[ |&]/.test(item) ? `(${item})[]` : `${item}[]`;
        }
        case 'object': throw new Error(`${file}: inline objects are not supported — move it to $defs with a title`);
        default: throw new Error(`${file}: unknown type ${t}`);
      }
    }).join(' | ');
  }

  // --------------------------------------------------------------------------- types.ts

  types() {
    let out = TS_BANNER;
    for (const [file, root] of this.set.schemas) {
      const entries = [];
      if (this.named.has(`${file}#`)) entries.push(root);
      for (const [k, def] of Object.entries(root.$defs ?? {})) {
        if (this.named.has(`${file}#/$defs/${k}`)) entries.push(def);
      }
      if (!entries.length) continue;
      out += `\n// ${'-'.repeat(96)}\n// ${file}\n`;
      for (const schema of entries) out += '\n' + this.declaration(schema, file);
    }
    return out;
  }

  declaration(schema, file) {
    const name = schema.title;
    let out = jsdoc({ description: schema.description, default: schema.default });
    if (schema.type === 'object') {
      const required = new Set(schema.required ?? []);
      out += `export interface ${name} {\n`;
      for (const [prop, ps] of Object.entries(schema.properties)) {
        out += jsdoc(this.annotations(ps, file), '  ');
        out += `  ${tsKey(prop)}${required.has(prop) ? '' : '?'}: ${this.tsType(ps, file)}\n`;
      }
      return out + '}\n';
    }
    out += `export type ${name} = ${this.tsType({ ...schema, title: undefined }, file)}\n`;
    if (schema.enum && schema.enum.every((v) => typeof v === 'string')) {
      out += `\n/** Every ${name}, in schema order. */\n`;
      out += `export const ${name}Values = [${schema.enum.map(tsLit).join(', ')}] as const\n`;
    }
    if (isConstUnion(schema)) {
      out += `\n/** ${name} values by name. */\nexport const ${name} = {\n`;
      for (const b of schema.oneOf) {
        if (!b.title || !isIdent(b.title)) throw new Error(`${file}: ${name}: every const branch needs an identifier title`);
        out += jsdoc({ description: b.description }, '  ');
        out += `  ${b.title}: ${tsLit(b.const)},\n`;
      }
      out += '} as const\n';
    }
    return out;
  }

  // ------------------------------------------------------------------- settings (limits)

  // One entry per ESP32 setting: { name, a: annotations, kind, min, max, members }.
  settings() {
    const root = this.set.schemas.get(SETTINGS_FILE);
    return Object.entries(root.$defs).map(([name, def]) => {
      const a = this.annotations(def, SETTINGS_FILE);
      const { schema: t } = this.typed(def, SETTINGS_FILE);
      const entry = { name, a, min: a.minimum, max: a.maximum };
      if (isConstUnion(t)) {
        const values = t.oneOf.map((b) => b.const);
        if (!values.every(Number.isInteger)) throw new Error(`${SETTINGS_FILE}: ${name}: only integer const unions are supported`);
        Object.assign(entry, { kind: 'integer', min: Math.min(...values), max: Math.max(...values), members: t.oneOf });
      } else if (['integer', 'number', 'boolean', 'string'].includes(t.type)) {
        entry.kind = t.type;
      } else {
        throw new Error(`${SETTINGS_FILE}: ${name}: unsupported setting type`);
      }
      if (entry.kind === 'integer' || entry.kind === 'number') {
        if (entry.min === undefined || entry.max === undefined) throw new Error(`${SETTINGS_FILE}: ${name}: numeric settings need a minimum and a maximum`);
      }
      if (!('default' in a)) throw new Error(`${SETTINGS_FILE}: ${name}: every setting needs a default`);
      if (typeof a.default === 'number' && (a.default < entry.min || a.default > entry.max)) {
        throw new Error(`${SETTINGS_FILE}: ${name}: default ${a.default} is outside ${entry.min}..${entry.max}`);
      }
      return entry;
    });
  }

  limits() {
    let out = TS_BANNER;
    out += '\n/**\n * ESP32 settings (protocol/schemas/esp32/settings.schema.json): valid range and the value of a\n';
    out += ' * fresh device. The device clamps out-of-range values (except `ip_octet`, which it rejects).\n';
    out += ' * Write-only settings (passwords) are left out.\n */\n';
    out += 'export const limits = {\n';
    for (const s of this.settings()) {
      if (s.a.writeOnly) continue;
      const fields = [];
      if (s.min !== undefined) fields.push(`min: ${s.min}`);
      if (s.max !== undefined) fields.push(`max: ${s.max}`);
      fields.push(`default: ${tsLit(s.a.default)}`);
      if (s.a['x-unit']) fields.push(`unit: ${tsLit(s.a['x-unit'])}`);
      out += jsdoc({ description: s.a.description }, '  ');
      out += `  ${tsKey(s.name)}: { ${fields.join(', ')} },\n`;
    }
    return out + '} as const\n';
  }

  // ------------------------------------------------------------------------ constants.ts

  groups() {
    return Object.entries(this.constants).filter(([k]) => k !== '$schema');
  }

  constantsTs() {
    let out = TS_BANNER;
    out += '\n/** Protocol constants (protocol/constants.json). */\nexport const constants = {\n';
    for (const [group, g] of this.groups()) {
      out += jsdoc({ description: g.description }, '  ');
      out += `  ${tsKey(group)}: {\n`;
      for (const [key, c] of Object.entries(g.values)) {
        out += jsdoc({ description: c.description }, '    ');
        out += `    ${tsKey(key)}: ${tsLit(c.value)},\n`;
      }
      out += '  },\n';
    }
    return out + '} as const\n';
  }

  // ------------------------------------------------------------------- ProtocolLimits.h

  header() {
    const lines = [];
    const block = (rows) => {
      // rows: [type, name, value, comment?] — aligned for readability.
      const wType = Math.max(...rows.map((r) => r[0].length));
      const wName = Math.max(...rows.map((r) => r[1].length));
      const wValue = Math.max(...rows.map((r) => r[2].length));
      for (const [type, name, value, comment] of rows) {
        const decl = `constexpr ${type.padEnd(wType)} ${name.padEnd(wName)} = ${value};`;
        lines.push(comment ? `${decl.padEnd(wType + wName + wValue + 15)} // ${comment}` : decl);
      }
    };

    lines.push(
      '// Generated by protocol/scripts/gen.mjs from protocol/ — do not edit.',
      '// Regenerate with `npm run protocol:gen` at the repo root.',
      '//',
      '// Header-only and free of Arduino includes, so host tests (pio test -e native) can use it.',
      '#pragma once',
      '',
      '#include <stdint.h>',
      '',
      'namespace protocol {',
    );

    lines.push('', `// ${'-'.repeat(76)}`, '// Constants (protocol/constants.json)');
    for (const [, g] of this.groups()) {
      if (!g.cppPrefix) continue;
      lines.push('', ...wrap(g.description, 97).map((l) => `// ${l}`));
      block(Object.entries(g.values).map(([key, c]) => {
        const name = `${g.cppPrefix}_${upperSnake(key)}`;
        if (typeof c.value === 'string') return ['const char*', name, cString(c.value), c.description];
        return [c.cppType ?? g.cppType ?? cppIntType(c.value, c.value), name, String(c.value), c.description];
      }));
    }

    lines.push('', `// ${'-'.repeat(76)}`, `// ESP32 settings (protocol/schemas/${SETTINGS_FILE})`,
      '// _MIN / _MAX: valid range (the device clamps out-of-range values, except IP_OCTET, which',
      '// it rejects). _DEFAULT: value of a fresh device.');
    for (const s of this.settings()) {
      const base = upperSnake(s.name);
      const text = `${s.name}: ${s.a.description ?? ''}${s.a['x-unit'] ? ` Unit: ${s.a['x-unit']}.` : ''}`;
      lines.push('', ...wrap(text, 97).map((l) => `// ${l}`));
      const rows = [];
      if (s.kind === 'integer' || s.kind === 'number') {
        const type = s.kind === 'number' ? 'float' : cppIntType(s.min, s.max);
        const num = (v) => (s.kind === 'number' ? cppFloat(v) : String(v));
        rows.push([type, `${base}_MIN`, num(s.min)], [type, `${base}_MAX`, num(s.max)], [type, `${base}_DEFAULT`, num(s.a.default)]);
        for (const m of s.members ?? []) rows.push([type, `${base}_${upperSnake(m.title)}`, num(m.const), m.description]);
      } else if (s.kind === 'boolean') {
        rows.push(['bool', `${base}_DEFAULT`, String(s.a.default)]);
      } else {
        rows.push(['const char*', `${base}_DEFAULT`, cString(s.a.default)]);
        if (s.a.pattern === '^#[0-9a-fA-F]{6}$') {
          rows.push(['uint32_t', `${base}_DEFAULT_RGB`, `0x${s.a.default.slice(1).toUpperCase()}`, 'the default as 0xRRGGBB']);
        }
      }
      block(rows);
    }

    lines.push('', '}  // namespace protocol', '');
    return lines.join('\n');
  }

  // Values that are defined in two places must agree.
  assertConsistent() {
    const esp32 = this.constants.esp32.values;
    const numLeds = this.set.schemas.get(SETTINGS_FILE).$defs.num_leds;
    const ledCount = this.set.schemas.get(COMMON_FILE).$defs.led_count;
    if (numLeds.maximum !== esp32.maxLeds.value) {
      throw new Error(`num_leds maximum (${numLeds.maximum}) != constants esp32.maxLeds (${esp32.maxLeds.value})`);
    }
    if (ledCount.maximum !== esp32.maxLedsPerSide.value) {
      throw new Error(`led_count maximum (${ledCount.maximum}) != constants esp32.maxLedsPerSide (${esp32.maxLedsPerSide.value})`);
    }
  }
}

function cppIntType(min, max) {
  if (min >= 0) {
    if (max <= 0xff) return 'uint8_t';
    if (max <= 0xffff) return 'uint16_t';
    if (max <= 0xffffffff) return 'uint32_t';
  } else if (min >= -0x80000000 && max <= 0x7fffffff) {
    return 'int32_t';
  }
  throw new Error(`no C++ integer type for ${min}..${max}`);
}

function cppFloat(v) {
  return Number.isInteger(v) ? `${v}.0f` : `${v}f`;
}

function cString(s) {
  if (!/^[\x20-\x7e]*$/.test(s)) throw new Error(`C++ string constants must be printable ASCII: ${JSON.stringify(s)}`);
  return JSON.stringify(s);
}

// Map of repo-relative output path → content.
export function generate() {
  const gen = new Generator(loadSchemas(), readJson(join(protocolDir, 'constants.json')));
  gen.assertConsistent();
  return new Map([
    [outputs.types, gen.types()],
    [outputs.limits, gen.limits()],
    [outputs.constants, gen.constantsTs()],
    [outputs.header, gen.header()],
  ]);
}

// Writes the outputs under outDir (default: the repo root).
export function writeOutputs(files, outDir = repoRoot) {
  for (const [rel, content] of files) {
    const path = join(outDir, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outDir = process.argv[2] ? resolve(process.argv[2]) : repoRoot;
  const files = generate();
  writeOutputs(files, outDir);
  for (const rel of files.keys()) console.log(`wrote ${rel}`);
}
